@contextmanager
def get_db():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        dsn = DATABASE_URL
        if dsn.startswith("postgres://"):
            dsn = "postgresql://" + dsn[len("postgres://"):]
        connection = psycopg.connect(dsn, connect_timeout=10, row_factory=dict_row)
    else:
        connection = sqlite3.connect(DATABASE_PATH, timeout=10)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def db_execute(db, query: str, params=()):
    if DATABASE_URL:
        query = query.replace("?", "%s")
    return db.execute(query, params)


def is_duplicate_username(error):
    return isinstance(error, sqlite3.IntegrityError) or getattr(error, "sqlstate", None) == "23505"


